// One-off generator for src/map/countryData.ts: downloads Natural Earth's 1:110m
// country boundaries (public domain) and writes them as compact border rings
// plus a label point and importance rank per country.
// Run from frontend/: node scripts/build-countries.mjs && npx prettier --write src/map/countryData.ts
import { writeFileSync } from 'node:fs'

const SOURCE =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson'
const OUT = new URL('../src/map/countryData.ts', import.meta.url)
const SOUTH_LIMIT = -60 // matches MAP_BOUNDS.south, same as build-land.mjs

const round = (n) => Math.round(n * 10) / 10 // 0.1 degree, same as WORLD_LAND

const geojson = await (await fetch(SOURCE)).json()

const countries = []
for (const { properties, geometry } of geojson.features) {
  // Polygons and MultiPolygons: keep outer rings only (index 0), no holes -
  // same simplification build-land.mjs makes for the coastline itself.
  const polygons =
    geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates
  const rings = []
  for (const polygon of polygons) {
    const ring = []
    for (const [lon, lat] of polygon[0]) {
      const point = [round(lon), round(lat)]
      const prev = ring.at(-1)
      if (!prev || prev[0] !== point[0] || prev[1] !== point[1])
        ring.push(point)
    }
    if (ring.length >= 3 && ring.some(([, lat]) => lat > SOUTH_LIMIT))
      rings.push(ring)
  }
  // Drops Antarctica (and any other feature left with no ring above the
  // south limit) the same way build-land.mjs's land polygons are dropped.
  if (rings.length === 0) continue

  countries.push({
    name: properties.NAME_EN,
    // 2-7: lower means "show at a lower zoom", used for label visibility.
    labelRank: properties.LABELRANK,
    // Natural Earth's own curated label point, not a computed centroid -
    // handles oddly-shaped/archipelago countries (Chile, Indonesia) well.
    label: [round(properties.LABEL_X), round(properties.LABEL_Y)],
    rings,
  })
}

const lines = countries.map(
  (c) =>
    `  { name: ${JSON.stringify(c.name)}, labelRank: ${c.labelRank}, label: ${JSON.stringify(c.label)}, rings: ${JSON.stringify(c.rings)} },`,
)
writeFileSync(
  OUT,
  [
    '// Generated by scripts/build-countries.mjs from Natural Earth 1:110m',
    '// admin-0 countries (public domain). Do not edit by hand.',
    'export interface Country {',
    '  name: string',
    '  labelRank: number // 2 (major) - 7 (minor); sets the font size in CountryBorders',
    '  label: [number, number] // [longitude, latitude] label anchor',
    '  rings: [number, number][][] // border ring(s), outer only, no holes',
    '}',
    '',
    'export const COUNTRIES: Country[] = [',
    ...lines,
    ']',
    '',
  ].join('\n'),
)
console.log(`Wrote ${countries.length} countries to ${OUT.pathname}`)
