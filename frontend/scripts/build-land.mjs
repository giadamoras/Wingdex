// One-off generator for src/map/worldLandData.ts: downloads Natural Earth's 1:110m land
// polygons (public domain) and writes them as compact [lon, lat] rings.
// Run from frontend/: node scripts/build-land.mjs
import { writeFileSync } from 'node:fs'

const SOURCE =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson'
const OUT = new URL('../src/map/worldLandData.ts', import.meta.url)
const SOUTH_LIMIT = -60 // matches MAP_BOUNDS.south: Antarctica is left out

const round = (n) => Math.round(n * 10) / 10 // 0.1 degree is plenty at 1:110m

const geojson = await (await fetch(SOURCE)).json()

const rings = []
for (const { geometry } of geojson.features) {
  // Polygons and MultiPolygons: keep outer rings only (index 0), no holes.
  const polygons =
    geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates
  for (const polygon of polygons) {
    const ring = []
    for (const [lon, lat] of polygon[0]) {
      const point = [round(lon), round(lat)]
      const prev = ring.at(-1)
      if (!prev || prev[0] !== point[0] || prev[1] !== point[1])
        ring.push(point)
    }
    if (ring.length >= 3 && ring.some(([, lat]) => lat > SOUTH_LIMIT))
      rings.push(ring)
  }
}

const lines = rings.map((ring) => `  ${JSON.stringify(ring)},`)
writeFileSync(
  OUT,
  [
    '// Generated by scripts/build-land.mjs from Natural Earth 1:110m land (public domain).',
    '// Do not edit by hand. Each ring is a list of [longitude, latitude] points.',
    'export const WORLD_LAND: [number, number][][] = [',
    ...lines,
    ']',
    '',
  ].join('\n'),
)
console.log(`Wrote ${rings.length} rings to ${OUT.pathname}`)
